import 'dart:math';

class FortuneGenerator {
  static final Random _random = Random();
  static String? _lastFortune;

  static const List<String> _builtInFortunes = [
    'Ця чашка кави заряджена на вдалий день та приємні несподіванки!',
    'Сьогодні доля роздасть тобі найкращі карти — навіть якщо це не Мафія.',
    'На тебе чекає гарна новина ще до того, як охолоне твій напій.',
    'Твоя інтуїція сьогодні працює безпомилково — довіряй їй.',
    'Попереду зустріч, яка подарує натхнення та щирий сміх.',
    'Усе задумане складеться легше, ніж здається на перший погляд.',
    'Сьогодні ідеальний вечір для перемоги у настільних іграх та теплих розмов.',
    'Маленька пауза з кавою зараз принесе велику ідею вже за годину.',
    'Всесвіт натякає: час потішити себе чимось смачненьким!',
    'Твоя енергія сьогодні притягує правильних людей та круті можливості.',
    'Навіть у найтемнішу ніч місто засинає, а твоя удача — ніколи.',
    'Цього тижня на тебе чекає приємний сюрприз, про який ти давно мріяв.',
    'Зроби ковток, усміхнись — найкраща частина дня тільки починається.',
    'Сьогодні ти саме в тому місці і в той час, де потрібно.',
    'Твоя наполегливість скоро принесе результат, яким ти пишатимешся.',
    'Зірки кажуть: вечір у хорошій компанії вирішить будь-яку втому.',
    'Нехай кожен ковток додає впевненості, а кожен день — приводів для радості.',
    'Сьогодні фортуна на твоєму боці — сміливо бери ініціативу!',
    'Гарний настрій — твоя суперсила на найближчі 24 години.',
    'Хтось поруч дуже цінує твою щирість та почуття гумору.',
    'Новий тиждень принесе несподіваний привід відсвяткувати маленьку перемогу.',
    'Сьогоднішній вибір напою був ідеальним — так само буде і з іншими рішеннями дня.',
    'Твій спокій та впевненість сьогодні стануть прикладом для інших.',
    'Попереду — затишний вечір, правильна музика і нуль зайвих турбот.',
  ];

  static const List<String> _openers = [
    'Сьогодні на тебе чекає',
    'Вже зовсім скоро у твоє життя увірветься',
    'Ця кава притягує до тебе',
    'Зірки над Кропивницьким віщують',
    'Найближчими днями тобі усміхнеться',
  ];

  static const List<String> _events = [
    'несподівана удача у важливій справі',
    'тепла зустріч із людьми на одній хвилі',
    'крута ідея, яка змінить плани на краще',
    'заслужений відпочинок та приємний бонус',
    'перемога там, де ти навіть не очікував',
  ];

  static const List<String> _closers = [
    '— просто насолоджуйся моментом!',
    '— не забудь загадати бажання!',
    '— усе складеться якнайкраще.',
    '— твій час сяяти!',
    '— бережи цей настрій.',
  ];

  /// Генерує випадкове передбачення без повтору попереднього підряд
  static String generate({List<String> customFortunes = const []}) {
    final allPool = <String>{
      ..._builtInFortunes,
      ...customFortunes.map((e) => e.trim()).where((e) => e.isNotEmpty),
    }.toList();

    // З імовірністю 30% створюємо унікальну комбіновану фразу з конструктора
    if (customFortunes.isEmpty && _random.nextInt(10) < 3) {
      for (int attempt = 0; attempt < 8; attempt++) {
        final opener = _openers[_random.nextInt(_openers.length)];
        final event = _events[_random.nextInt(_events.length)];
        final closer = _closers[_random.nextInt(_closers.length)];
        final combined = '$opener $event $closer';
        if (combined != _lastFortune) {
          _lastFortune = combined;
          return combined;
        }
      }
    }

    final candidates = allPool.length > 1
        ? allPool.where((f) => f != _lastFortune).toList()
        : allPool;

    final chosen = candidates[_random.nextInt(candidates.length)];
    _lastFortune = chosen;
    return chosen;
  }
}