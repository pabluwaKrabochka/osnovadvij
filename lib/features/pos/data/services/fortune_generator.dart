    'Цього тижня на тебе чекає приємний сюрприз, про який ти давно мріяв.',
    'Зроби ковток, усміхнись — найкраща частина дня тільки починається.',
    'Сьогодні ти саме в тому місці і в той час, де потрібно.',
    'Твоя наполегливість скоро принесе результат, яким ти пишатимешся.',
    'Зірки кажуть: вечір у хорошій компанії вирішить будь-яку втому.',
    'Нехай кожен ковток додає впевненості, а кожен день — приводів для радості.',
