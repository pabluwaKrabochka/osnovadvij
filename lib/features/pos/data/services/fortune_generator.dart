    'Попереду — затишний вечір, правильна музика і нуль зайвих турбот.',
  ];

  static const List<String> _openers = [
    'Сьогодні на тебе чекає',
    'Вже зовсім скоро у твоє життя увірветься',
    'Ця кава притягує до тебе',
    'Зірки над Кропивницьким віщують',
    'Найближчими днями тобі усміхнеться',
  ];

  static const List<String> _events = [
    'несподівана удача у важливій справі',
    'тепла зустріч із людьми на одній хвилі',
    'крута ідея, яка змінить плани на краще',
    'заслужений відпочинок та приємний бонус',
    'перемога там, де ти навіть не очікував',
  ];

  static const List<String> _closers = [
    '— просто насолоджуйся моментом!',
    '— не забудь загадати бажання!',
    '— усе складеться якнайкраще.',
    '— твій час сяяти!',
    '— бережи цей настрій.',
  ];

  /// Генерує випадкове передбачення (з урахуванням власних фраз закладу)
  static String generate({List<String> customFortunes = const []}) {
    final allPool = <String>[
      ..._builtInFortunes,
      ...customFortunes.where((e) => e.trim().isNotEmpty),
    ];

    // З імовірністю 30% створюємо унікальну комбіновану фразу з конструктора
